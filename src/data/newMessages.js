/**
 * Возвращает случайное сообщение для новой фигурки.
 * @param {string} rarityId — 'D' | 'C' | 'B' | 'A' | 'S' | 'SS+'
 */
export function getNewMessage(rarityId) {
  const pool = NEW_MESSAGES[rarityId] || NEW_MESSAGES.D;
  return pool[Math.floor(Math.random() * pool.length)];
}